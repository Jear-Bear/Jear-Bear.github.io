// make-clips.mjs — turns the workflow's library.json into scripts/pitch/data/clips.js.
// Usage: node scripts/pitch/build/make-clips.mjs path/to/build-output
// (the folder from the pitch-audio-build branch: library.json, traces.json, audio/).
// Keeps word recordings whose pitch matches the dictionary accent, one per word
// (public-domain first, then the clearest), plus the phrase recordings; marks
// minimal pairs; adds guide-tone clips for classic pairs nobody has recorded
// yet; recomputes each target contour with the current engine; and copies the
// MP3s it uses into tools/pitch/audio/.
import fs from 'fs';
import path from 'path';
import { normalizeTrace, resample, synthContour, moraPattern } from '../engine/contour.js';
import { patternScore, shapeScore } from '../engine/scoring.js';

const HERE = path.dirname(new URL(import.meta.url).pathname);
// Commons titles of recordings that sound off to a human ear; never use these
const SKIP = new Set([]);
const SRC = process.argv[2];
const traces = JSON.parse(fs.readFileSync(path.join(SRC, 'traces.json'), 'utf8'));
const curveOf = (id) => normalizeTrace(traces[id].map(([t, hz]) => ({ t: t / 1000, hz }))).points;
const lib = JSON.parse(fs.readFileSync(path.join(SRC, 'library.json'), 'utf8')).filter((c) => {
  if (!traces[c.id]) return false;
  // speakers left out: likely not native Japanese speakers
  if (/I JethroBT/.test(c.credit.author)) return false;
  if (SKIP.has(c.title)) return false;
  const pts = curveOf(c.id);
  if (pts.length < 6) return false;
  c.contour = resample(pts, 64).map((v) => Math.round(v * 100) / 100);
  c.credit.author = c.credit.author.replace(/^Speaker:\s*/, '').split('\n')[0].trim();
  if (c.type !== 'word') return true;
  const target = c.pattern.kind === 'heiban' || c.pattern.kind === 'odaka' ? 0 : c.pattern.drop;
  // the drop has to land in the right place AND the whole shape has to look
  // like the textbook pattern, so learners copy a clean example
  const ideal = synthContour(moraPattern(c.pattern.kind, c.pattern.drop, c.moras.length));
  return patternScore(pts, c.moras.length, target).pass && shapeScore(pts, ideal) >= 60;
});
const licRank = { CC0: 0, 'CC BY 4.0': 1, 'CC BY-SA 4.0': 2 };
const better = (a, b) => (licRank[a.credit.license] - licRank[b.credit.license]) || ((b.voiced || 0) - (a.voiced || 0));

const words = new Map();
const sentences = new Map();
for (const c of lib) {
  const key = c.type === 'word' ? `${c.text}|${c.reading}` : c.text;
  const m = c.type === 'word' ? words : sentences;
  if (!m.has(key) || better(c, m.get(key)) < 0) m.set(key, c);
}

// Classic minimal pairs (accents checked against Kanjium). Recorded versions win;
// the rest play a guide tone so the pair still works.
const CLASSIC = [
  ['箸', 'はし', 1], ['橋', 'はし', 2], ['端', 'はし', 0],
  ['雨', 'あめ', 1], ['飴', 'あめ', 0],
  ['牡蠣', 'かき', 1], ['柿', 'かき', 0],
  ['神', 'かみ', 1], ['紙', 'かみ', 2],
  ['鮭', 'さけ', 1], ['酒', 'さけ', 0],
  ['鼻', 'はな', 0], ['花', 'はな', 2],
  ['朝', 'あさ', 1], ['麻', 'あさ', 2],
  ['切る', 'きる', 1], ['着る', 'きる', 0],
  ['今', 'いま', 1], ['居間', 'いま', 2],
];
const SMALL = new Set([...'ゃゅょぁぃぅぇぉゎャュョァィゥェォヮ']);
const moras = (r) => { const a = []; for (const ch of r) { if (SMALL.has(ch) && a.length) a[a.length - 1] += ch; else a.push(ch); } return a; };
const kindOf = (acc, n) => (acc === 0 ? 'heiban' : acc === 1 ? 'atamadaka' : acc === n ? 'odaka' : 'nakadaka');
for (const [text, reading, acc] of CLASSIC) {
  if (words.has(`${text}|${reading}`)) continue;
  const m = moras(reading);
  words.set(`${text}|${reading}`, { id: `tone-${reading}-${acc}`, text, reading, moras: m, type: 'word', pattern: { kind: kindOf(acc, m.length), drop: acc } });
}

// minimal pairs: same reading, different accent
const byReading = {};
for (const w of words.values()) (byReading[w.reading] ||= new Set()).add(w.pattern.drop);
const out = [];
for (const w of words.values()) {
  const e = { id: w.id, text: w.text, reading: w.reading, moras: w.moras, type: 'word', pattern: w.pattern };
  if (byReading[w.reading].size > 1) e.pair = w.reading;
  if (w.audio) Object.assign(e, { audio: w.audio, contour: w.contour, credit: w.credit });
  out.push(e);
}
for (const s of sentences.values()) {
  out.push({ id: s.id, text: s.text, reading: '', moras: [], type: 'sentence', pattern: {}, audio: s.audio, contour: s.contour, credit: s.credit });
}
out.sort((a, b) => (a.type > b.type ? -1 : a.type < b.type ? 1 : a.reading.localeCompare(b.reading, 'ja')));

const header = `// clips.js — GENERATED by scripts/pitch/build/make-clips.mjs. Don't edit by hand.
// Recordings: Lingua Libre speakers on Wikimedia Commons (CC0 / CC BY 4.0 /
// CC BY-SA 4.0; per-clip credit below). Accents: Kanjium (CC BY-SA 4.0,
// https://github.com/mifunetoshiro/kanjium). Each recording was checked: its
// pitch drop had to match the dictionary accent to be included.
//
// pattern.kind: 'heiban' | 'atamadaka' | 'nakadaka' | 'odaka'
// pattern.drop: the mora after which pitch falls (0 = never; odaka = mora count,
//               so the fall lands on the next particle). Clips without audio
//               play a guide tone instead of a voice.
`;
const body = `export const KINDS = [['heiban', 'Heiban (flat)'], ['atamadaka', 'Atamadaka (head-high)'], ['nakadaka', 'Nakadaka (middle-high)'], ['odaka', 'Odaka (tail-high)']];

export const CLIPS = ${JSON.stringify(out)};
`;
const dest = path.join(HERE, '..', 'data', 'clips.js');
fs.writeFileSync(dest, header + '\n' + body);
const audioDir = path.join(HERE, '..', '..', '..', 'tools', 'pitch', 'audio');
fs.rmSync(audioDir, { recursive: true, force: true });
fs.mkdirSync(audioDir, { recursive: true });
for (const c of out) if (c.audio) fs.copyFileSync(path.join(SRC, c.audio), path.join(audioDir, path.basename(c.audio)));
const n = (f) => out.filter(f).length;
console.log(`${out.length} clips: ${n((c) => c.type === 'word')} words (${n((c) => c.audio && c.type === 'word')} recorded), ${n((c) => c.pair)} in pairs, ${n((c) => c.type === 'sentence')} sentences`);
